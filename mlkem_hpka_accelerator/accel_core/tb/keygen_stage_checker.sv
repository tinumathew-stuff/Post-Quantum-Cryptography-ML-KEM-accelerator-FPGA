`timescale 1ns/1ps

//==================================================================================================
// File Name   : keygen_stage_checker.sv
// Project     : High-Performance ML-KEM Hardware Accelerator (FIPS 203 Post-Quantum Cryptography)
// Target Tech : Simulation Only (Vivado Simulator, VCS, ModelSim / QuestaSim)
// Verification: White-Box Stage-by-Stage Verification Monitor for KeyGen Pipeline
// Author      : Accelerated Cryptography Engineering Group
// Description :
//   Passive simulation verification monitor and assertion checker for the ML-KEM Key Generation
//   pipeline (`mlkem_keygen_top`).
//
//   Rather than solely evaluating end-to-end key correctness at the completion of KeyGen,
//   this module non-intrusively monitors internal DUT registers and streaming buses cycle-by-cycle.
//   It isolates functional regressions to the exact pipeline stage where corruption first occurs:
//
//   Pipeline Stages Monitored:
//     1. Root Seed Expansion & Hashing: Monitored at G(d || k) digest generation.
//     2. Secret Vector Noise Sampling (s): CBD sampler output in DUT FSM state 3 (SamplePolyCBD).
//     3. Error Vector Noise Sampling (e):  CBD sampler output in DUT FSM state 4 (SamplePolyCBD).
//     4. Public Matrix Expansion (A):      Rejection sampler output in DUT FSM state 5 (SampleNTT).
//     5. Number Theoretic Transform (NTT): NTT streaming length and error flag monitoring.
//     6. Prefetch / Restore Concurrency:   Hazard detector ensuring prefetch in Keccak core is
//                                          never overwritten upon matrix polynomial completion.
//
//   Reference Hex Data:
//     Loads golden intermediate polynomial vectors generated by the bit-exact C reference
//     implementation (`stage_matrix_k%0d.hex`, `stage_s_k%0d.hex`, `stage_e_k%0d.hex`).
//
//==================================================================================================

// Simulation hierarchy macro pointing to the instantiated Device Under Test (DUT)
`define DUT tb_mlkem_keygen_top.dut

module keygen_stage_checker;

    //==============================================================================================
    // Golden Reference Storage Arrays
    // Pre-allocated for the maximum supported lattice rank (k = 4, ML-KEM-1024):
    //   - matrix_ref: k * k * 256 coefficients = 4 * 4 * 256 = 4096 coefficients (12 bits each)
    //   - s_ref     : k * 256 coefficients     = 4 * 256     = 1024 coefficients (12 bits each)
    //   - e_ref     : k * 256 coefficients     = 4 * 256     = 1024 coefficients (12 bits each)
    //==============================================================================================
    logic [11:0] matrix_ref [0:4095];
    logic [11:0] s_ref [0:1023], e_ref [0:1023];

    // Tracking indices and cumulative transfer counters
    integer sample_index;
    integer matrix_count, s_count, e_count, ntt_count, completion_overlap_count;

    //==============================================================================================
    // Synchronous Monitoring Process
    // Triggered on every rising edge of DUT system clock
    //==============================================================================================
    always @(posedge `DUT.clk) begin
        //------------------------------------------------------------------------------------------
        // Asynchronous / Synchronous Reset Handling
        //------------------------------------------------------------------------------------------
        if (!`DUT.rst_n) begin
            sample_index             = 0;
            matrix_count             = 0;
            s_count                  = 0;
            e_count                  = 0;
            ntt_count                = 0;
            completion_overlap_count = 0;
        end else begin
            //--------------------------------------------------------------------------------------
            // Hazard Check: Matrix Completion & Keccak Prefetch Concurrency
            // In ML-KEM-1024 (k = 4), an added FIFO stage makes this boundary condition reachable.
            // When the final beat of a matrix polynomial finishes (`mat_done_beat`) exactly when
            // Keccak block_idx_q == 3 and core is ready, the next polynomial's Keccak permutation
            // must NOT be overwritten by a spurious restore trigger or core start strobe.
            //--------------------------------------------------------------------------------------
            if (`DUT.hash_sampler_inst.fsm_q[5] &&
                `DUT.hash_sampler_inst.block_idx_q == 3 &&
                `DUT.hash_sampler_inst.core_ready && `DUT.hash_sampler_inst.mat_done_beat) begin
                completion_overlap_count++;
                if (`DUT.hash_sampler_inst.mat_restore_trig || `DUT.hash_sampler_inst.core_start)
                    $fatal(1, "Matrix completion overwrites prefetched polynomial k=%0d", `DUT.k_q);
            end

            //--------------------------------------------------------------------------------------
            // NTT Subsystem Protocol Error Assertion
            // Fires immediately if the NTT core asserts its command/stream error flag
            //--------------------------------------------------------------------------------------
            if (`DUT.ntt_cmd_error)
                $fatal(1, "NTT rejected the integration stream k=%0d", `DUT.k_q);

            //--------------------------------------------------------------------------------------
            // Testbench Start Strobe: Load Parameter-Specific Reference Data
            // When DUT asserts ready and receives start, load golden intermediate stage vectors
            // corresponding to the active rank k \in {2, 3, 4}.
            //--------------------------------------------------------------------------------------
            if (`DUT.start && `DUT.ready) begin
                $readmemh($sformatf("stage_matrix_k%0d.hex", `DUT.k), matrix_ref, 0, `DUT.k*`DUT.k*256-1);
                $readmemh($sformatf("stage_s_k%0d.hex", `DUT.k), s_ref, 0, `DUT.k*256-1);
                $readmemh($sformatf("stage_e_k%0d.hex", `DUT.k), e_ref, 0, `DUT.k*256-1);
                matrix_count             = 0;
                s_count                  = 0;
                e_count                  = 0;
                ntt_count                = 0;
                completion_overlap_count = 0;
            end

            // Reset polynomial sample index when sampler begins a new command
            if (`DUT.sampler_cmd_valid && `DUT.sampler_cmd_ready)
                sample_index = 0;

            //--------------------------------------------------------------------------------------
            // Sampler Stream Verification (s, e, and Matrix A)
            // Validates framing metadata and bit-exact coefficient correctness
            //--------------------------------------------------------------------------------------
            if (`DUT.sampler_out_valid && `DUT.sampler_out_ready) begin
                // Protocol assertion: framing must strictly adhere to 4 coefficients per beat,
                // matching expected polynomial index and end-of-polynomial (coeff 252) indicator.
                if (`DUT.sampler_out_count !== 3'd4 ||
                    `DUT.sampler_out_poly_index !== (sample_index / 256) ||
                    `DUT.sampler_out_last !== ((sample_index % 256) == 252))
                    $fatal(1, "Invalid sampler framing k=%0d coefficient=%0d", `DUT.k_q, sample_index);

                // Bit-exact coefficient comparison across all 4 parallel lanes
                for (int lane = 0; lane < 4; lane++) begin
                    case (`DUT.fsm_q)
                        3: if (`DUT.sampler_out_data[lane*12 +: 12] !== s_ref[sample_index+lane])
                            $fatal(1, "S sampling mismatch k=%0d coefficient=%0d", `DUT.k_q, sample_index+lane);
                        4: if (`DUT.sampler_out_data[lane*12 +: 12] !== e_ref[sample_index+lane])
                            $fatal(1, "E sampling mismatch k=%0d coefficient=%0d", `DUT.k_q, sample_index+lane);
                        5: if (`DUT.sampler_out_data[lane*12 +: 12] !== matrix_ref[sample_index+lane])
                            $fatal(1, "Matrix sampling mismatch k=%0d coefficient=%0d got=%03x expected=%03x", `DUT.k_q, sample_index+lane, `DUT.sampler_out_data[lane*12 +: 12], matrix_ref[sample_index+lane]);
                    endcase
                end

                // Accumulate per-stage transfer count
                case (`DUT.fsm_q)
                    3: s_count += 4;
                    4: e_count += 4;
                    5: matrix_count += 4;
                endcase
                sample_index += 4;
            end

            //--------------------------------------------------------------------------------------
            // NTT Stream Throughput Accounting
            // Each NTT beat transfers 2 coefficients (24 bits) across the pipeline
            //--------------------------------------------------------------------------------------
            if (`DUT.ntt_out_valid && `DUT.ntt_out_ready) begin
                ntt_count += 2;
            end

            //--------------------------------------------------------------------------------------
            // End-of-KeyGen Pipeline Stage Summary and Completeness Check
            // In DUT FSM state 6 (Hash / Key Formatting), when sampler digest is asserted,
            // verify that every stage processed the exact expected total number of coefficients.
            //--------------------------------------------------------------------------------------
            if (`DUT.fsm_q == 6 && `DUT.sampler_digest_valid) begin
                if (s_count != `DUT.k_q*256 || e_count != `DUT.k_q*256 ||
                    matrix_count != `DUT.k_q*`DUT.k_q*256 || ntt_count != `DUT.k_q*512)
                    $fatal(1, "Incomplete stage streams k=%0d", `DUT.k_q);

                // For k=4, ensure that the regression actually exercised the corner case
                if (`DUT.k_q == 4 && completion_overlap_count == 0)
                    $fatal(1, "k=4 regression did not exercise simultaneous completion/restore");

                $display("   [PASS] All sampler coefficients/framing and NTT stream lengths verified for k=%0d (completion/restore overlaps=%0d)", `DUT.k_q, completion_overlap_count);
            end
        end
    end

endmodule

`undef DUT
