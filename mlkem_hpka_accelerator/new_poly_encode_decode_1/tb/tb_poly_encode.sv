`timescale 1ns/1ps
//==============================================================================
// Testbench: tb_poly_encode
// Description: Comprehensive Self-Checking Testbench for the ML-KEM / FIPS 203
//              poly_encode (ByteEncode_d) Hardware Accelerator.
//
// Verification Scope & Capabilities:
//   1. Multi-Parameter Space Coverage:
//      Validates polynomial encoding across all FIPS 203 specified bit-widths:
//        - d = 1  (ML-KEM-512/768/1024 c2 vector compression: 256 bits -> 32 bytes)
//        - d = 4  (ML-KEM-512 u vector compression: 1024 bits -> 128 bytes)
//        - d = 5  (ML-KEM-768/1024 u vector compression: 1280 bits -> 160 bytes)
//        - d = 10 (ML-KEM-512/768 u vector compression: 2560 bits -> 320 bytes)
//        - d = 11 (ML-KEM-1024 u vector compression: 2816 bits -> 352 bytes)
//        - d = 12 (Uncompressed ring elements R_q: 3072 bits -> 384 bytes)
//
//   2. Comprehensive Traffic & Backpressure Profiles (11 Modes):
//      Evaluates datapath integrity and zero-bubble buffering under diverse
//      boundary, starvation, and congestion scenarios:
//        - Mode 0  (BP_NONE): Full-bandwidth stream, zero bubbles, out_ready = 1.
//        - Mode 1  (BP_LIGHT): Light pseudo-random bubbles on source and sink.
//        - Mode 2  (BP_SINK_90): Heavy downstream backpressure (90% stall rate).
//        - Mode 3  (BP_SINK_95): Extreme downstream backpressure (95% stall rate).
//        - Mode 4  (BP_SINK_BURST): Periodic drain bursts (5 drain cycles, 25 stall cycles).
//        - Mode 5  (BP_SRC_STARVE): Severe upstream source starvation (85% idle cycles).
//        - Mode 6  (BP_COMBINED): Combined upstream starvation and downstream stalls.
//        - Mode 7  (BP_PINGPONG): Cycle-by-cycle alternating valid/ready toggle.
//        - Mode 8  (BP_START_STALL): Prolonged 30-cycle stall at packet transmission start.
//        - Mode 9  (BP_MID_STALL): Prolonged 30-cycle stall at packet midpoint.
//        - Mode 10 (BP_BURST): Coordinated periodic burst transactions.
//
//   3. AXI4-Stream Protocol Stability Enforcement:
//      Formally verifies that when out_valid is asserted and out_ready is low
//      (wait state), out_data and out_last remain absolutely invariant until
//      the handshake completes. Flags any stability violations as fatal protocol errors.
//
//   4. Golden Vector Comparison & Framing Verification:
//      Performs cycle-accurate scoreboard matching against pre-computed golden
//      hex files generated by the reference model. Validates that out_last asserts
//      strictly on the terminal byte of each polynomial.
//==============================================================================

`include "sim/vector_meta.vh"

module tb_poly_encode;

    //--------------------------------------------------------------------------
    // Clock Generation: 450 MHz target frequency (2.222 ns period)
    // Simulates timing-closed operation on Xilinx Kintex UltraScale (xcku035)
    //--------------------------------------------------------------------------
    logic clk = 0;
    always #1.111 clk = ~clk; // 450 MHz clock (2.222 ns period)

    //--------------------------------------------------------------------------
    // DUT Interface Signals
    //--------------------------------------------------------------------------
    logic        rst_n = 0;     // Active-low asynchronous reset
    logic [3:0]  cfg_d = 4'd12; // Runtime bit-width parameter d in {1, 4, 5, 10, 11, 12}
    logic        in_valid = 0;  // Upstream coefficient valid strobe
    logic        in_ready;      // DUT ready to accept coefficient
    logic [11:0] in_data = 0;   // Upstream 12-bit ring coefficient a_i
    logic        in_last = 0;   // Upstream last-coefficient stream marker
    logic        out_valid;     // Downstream byte valid strobe from DUT
    logic        out_ready = 0; // Downstream consumer ready strobe
    logic [7:0]  out_data;      // Downstream serialized byte data from DUT
    logic        out_last;      // Downstream last-byte stream marker from DUT

    //--------------------------------------------------------------------------
    // Command Descriptor Format
    // Matches the binary record format produced by the test vector generator
    //--------------------------------------------------------------------------
    typedef struct packed {
        logic [3:0]  d;          // Bit-width configuration (1, 4, 5, 10, 11, 12)
        logic [3:0]  bp_mode;    // Backpressure profile selection (0 to 10)
        logic [15:0] words_in;   // Number of input coefficients (256 per poly)
        logic [15:0] words_out;  // Number of expected output bytes (32 * d)
        logic [31:0] offset_in;  // Offset index in vec_in memory array
        logic [31:0] offset_out; // Offset index in vec_exp memory array
    } cmd_desc_t;

    // Test vector storage tables loaded from hex files
    cmd_desc_t  cmd_table [0:`ENC_NUM_CMDS - 1];
    logic [11:0] vec_in    [0:`ENC_TOTAL_WORDS_IN - 1];
    logic [7:0]  vec_exp   [0:`ENC_TOTAL_WORDS_OUT - 1];

    // Verification metrics and bookkeeping counters
    integer cycle_count = 0;          // Cumulative simulation cycle counter
    integer command_start = 0;        // Timestamp marking the start of current command
    integer failures = 0;             // Total count of data mismatches and framing errors
    integer stability_violations = 0; // Total count of AXI-Stream protocol stability errors

    //--------------------------------------------------------------------------
    // Device Under Test (DUT) Instantiation
    //--------------------------------------------------------------------------
    poly_encode dut (
        .clk       (clk),
        .rst_n     (rst_n),
        .cfg_d     (cfg_d),
        .in_valid  (in_valid),
        .in_ready  (in_ready),
        .in_data   (in_data),
        .in_last   (in_last),
        .out_valid (out_valid),
        .out_ready (out_ready),
        .out_data  (out_data),
        .out_last  (out_last)
    );

    //--------------------------------------------------------------------------
    // Test Vector Ingestion
    // Loads command table, input coefficients, and golden reference bytes
    //--------------------------------------------------------------------------
    initial begin
        $readmemh("sim/encode_commands.hex", cmd_table);
        $readmemh("sim/encode_in.hex", vec_in);
        $readmemh("sim/encode_expected.hex", vec_exp);
    end

    //--------------------------------------------------------------------------
    // Watchdog Monitor
    // Guards against simulation hang or handshake deadlock in DUT
    //--------------------------------------------------------------------------
    always @(posedge clk) begin
        cycle_count <= cycle_count + 1;
        if (cycle_count > 5000000) $fatal(1, "WATCHDOG TIMEOUT at cycle %0d", cycle_count);
    end

    //--------------------------------------------------------------------------
    // Task: run_test
    // Description: Executes one complete polynomial encode test command.
    //              Coordinates concurrent source injection and sink verification
    //              threads via a parallel fork-join block.
    //--------------------------------------------------------------------------
    task automatic run_test(input integer cmd_idx);
        cmd_desc_t desc;
        integer words_in, words_out;
        integer offset_in, offset_out;
        integer sent, got;
        integer gap_count;
        logic [7:0] prev_out_data;
        logic       prev_out_last;
        logic       prev_valid_stalled;
        integer     stall_counter;

        begin
            // Unpack command descriptor parameters
            desc       = cmd_table[cmd_idx];
            words_in   = integer'(desc.words_in);
            words_out  = integer'(desc.words_out);
            offset_in  = integer'(desc.offset_in);
            offset_out = integer'(desc.offset_out);

            // Configure DUT bit-width on negative clock edge to avoid race conditions
            @(negedge clk);
            cfg_d     = desc.d;
            out_ready = 1'b0;

            // Initialize test tracking variables
            sent               = 0;
            got                = 0;
            gap_count          = 0;
            prev_valid_stalled = 1'b0;
            stall_counter      = 0;
            command_start      = cycle_count;

            fork
                //==============================================================
                // SOURCE PROCESS: Drives in_valid, in_data, in_last
                // Models diverse upstream producer pressure profiles
                //==============================================================
                begin: SOURCE
                    logic drive_valid;
                    integer burst_timer;
                    burst_timer = 0;

                    while (sent < words_in) begin
                        @(negedge clk);
                        drive_valid = 1'b1;

                        // Evaluate source valid drive condition based on bp_mode
                        case (desc.bp_mode)
                            4'd0: drive_valid = 1'b1; // BP 0: Full speed
                            4'd1: if ((sent + gap_count + cmd_idx) % 7 == 3) drive_valid = 1'b0; // BP 1: Light bubbles
                            4'd2, 4'd3, 4'd4: drive_valid = 1'b1; // Sink-focused pressure
                            4'd5: drive_valid = (($urandom % 100) < 15); // BP 5: Severe starvation (85% idle)
                            4'd6: drive_valid = (($urandom % 100) < 30); // BP 6: Combined starvation & sink backpressure
                            4'd7: drive_valid = (cycle_count % 2 == 0);  // BP 7: Pingpong toggle
                            4'd8, 4'd9: drive_valid = 1'b1;              // Sink stalls
                            4'd10: begin // BP 10: Burst
                                burst_timer = burst_timer + 1;
                                drive_valid = (burst_timer % 30 < 10);
                            end
                            default: drive_valid = 1'b1;
                        endcase

                        // Apply stimulus signals to input bus
                        if (drive_valid) begin
                            in_valid = 1'b1;
                            in_data  = vec_in[offset_in + sent];
                            in_last  = (sent == words_in - 1);
                        end else begin
                            in_valid = 1'b0;
                            in_data  = 12'hx;
                            in_last  = 1'b0;
                            gap_count = gap_count + 1;
                        end

                        // Sample handshake completion at clock posedge
                        @(posedge clk);
                        if (in_valid && in_ready) begin
                            sent = sent + 1;
                        end
                    end

                    // Deassert input bus once all coefficients are transferred
                    @(negedge clk);
                    in_valid = 1'b0;
                    in_last  = 1'b0;
                end

                //==============================================================
                // SINK PROCESS: Drives out_ready, validates data and stability
                // Models downstream consumer backpressure and verifies output bytes
                //==============================================================
                begin: SINK
                    logic drive_ready;
                    integer mid_point;
                    mid_point = words_out / 2;

                    while (got < words_out) begin
                        @(negedge clk);

                        // Evaluate downstream consumer ready condition based on bp_mode
                        case (desc.bp_mode)
                            4'd0: drive_ready = 1'b1; // BP 0: Full speed
                            4'd1: drive_ready = (((cycle_count - command_start) % 5) != 2); // BP 1: Light sink stalls
                            4'd2: drive_ready = (($urandom % 100) < 10); // BP 2: 90% sink stall
                            4'd3: drive_ready = (($urandom % 100) < 5);  // BP 3: 95% sink stall
                            4'd4: drive_ready = (((cycle_count - command_start) % 30) < 5); // BP 4: 5 drain, 25 stall
                            4'd5: drive_ready = 1'b1;
                            4'd6: drive_ready = (($urandom % 100) < 20); // BP 6: Combined
                            4'd7: drive_ready = (cycle_count % 2 == 1);  // BP 7: Pingpong
                            4'd8: begin // BP 8: 30 cycles stall at start of stream
                                if (out_valid && stall_counter < 30) begin
                                    drive_ready = 1'b0;
                                    stall_counter = stall_counter + 1;
                                end else drive_ready = 1'b1;
                            end
                            4'd9: begin // BP 9: 30 cycles stall midway through stream
                                if (got >= mid_point && stall_counter < 30) begin
                                    drive_ready = 1'b0;
                                    stall_counter = stall_counter + 1;
                                end else drive_ready = 1'b1;
                            end
                            4'd10: drive_ready = (((cycle_count - command_start) % 25) < 7);
                            default: drive_ready = 1'b1;
                        endcase

                        out_ready = drive_ready;

                        //------------------------------------------------------
                        // AXI4-Stream Protocol Stability Check:
                        // Payload (out_data, out_last) must remain invariant
                        // throughout backpressured cycles (out_valid && !out_ready)
                        //------------------------------------------------------
                        if (out_valid && !out_ready) begin
                            if (prev_valid_stalled) begin
                                if (out_data !== prev_out_data || out_last !== prev_out_last) begin
                                    $display("[PROTOCOL ERROR] Output changed while stalled! Cmd %0d Byte %0d", cmd_idx, got);
                                    stability_violations = stability_violations + 1;
                                    failures = failures + 1;
                                end
                            end
                            prev_out_data       = out_data;
                            prev_out_last       = out_last;
                            prev_valid_stalled  = 1'b1;
                        end else begin
                            prev_valid_stalled  = 1'b0;
                        end

                        //------------------------------------------------------
                        // Output Handshake Sampling & Scoreboard Verification
                        //------------------------------------------------------
                        @(posedge clk);
                        if (out_valid && out_ready) begin
                            logic [7:0] exp_val;
                            exp_val = vec_exp[offset_out + got];

                            // Validate byte payload against golden reference
                            if (out_data !== exp_val) begin
                                $display("[MISMATCH ERROR] Cmd %0d (d=%0d bp=%0d) Byte %0d: got %02x, exp %02x",
                                         cmd_idx, desc.d, desc.bp_mode, got, out_data, exp_val);
                                failures = failures + 1;
                                if (failures > 20) $fatal(1, "Too many test failures encountered!");
                            end

                            // Validate out_last packet framing signal
                            if (out_last !== (got == words_out - 1)) begin
                                $display("[LAST SIGNAL ERROR] Cmd %0d Byte %0d: out_last=%0b expected=%0b",
                                         cmd_idx, got, out_last, (got == words_out - 1));
                                failures = failures + 1;
                            end

                            got = got + 1;
                        end
                    end

                    // Deassert consumer ready at the completion of packet reception
                    @(negedge clk);
                    out_ready = 1'b0;
                end
            join
        end
    endtask

    //--------------------------------------------------------------------------
    // Main Verification Execution Flow
    //--------------------------------------------------------------------------
    initial begin
        $display("================================================================================");
        $display("Starting poly_encode verification (%0d test commands across d={1,4,5,10,11,12})", `ENC_NUM_CMDS);
        $display("Testing across 11 backpressure profiles with protocol stability enforcement.");
        $display("================================================================================");

        // Reset Sequence
        rst_n = 0;
        in_valid = 0;
        in_last = 0;
        out_ready = 0;
        repeat (10) @(posedge clk);
        @(negedge clk);
        rst_n = 1;
        repeat (5) @(posedge clk);

        // Command Execution Loop across all test vectors
        for (integer c = 0; c < `ENC_NUM_CMDS; c++) begin
            run_test(c);
            if ((c + 1) % 10 == 0 || c == `ENC_NUM_CMDS - 1) begin
                $display("  Progress: %0d / %0d commands verified successfully (cycle %0d)", c + 1, `ENC_NUM_CMDS, cycle_count);
            end
        end

        // Final Verification Summary
        $display("================================================================================");
        if (failures == 0 && stability_violations == 0) begin
            $display("ALL %0d POLY_ENCODE COMMANDS PASSED WITH 0 ERRORS! (Cycles: %0d)", `ENC_NUM_CMDS, cycle_count);
            $display("Backpressure stability: 100%% compliant.");
        end else begin
            $display("TEST FAILED! Total errors: %0d (Stability violations: %0d)", failures, stability_violations);
        end
        $display("================================================================================");
        $finish;
    end

endmodule
